// Generates packages/design-tokens/fonts.css from the @fontsource packages.
// Fonts are served by the Express server at /static/fonts (the SPA uses the same origin), so one
// stylesheet works for SSR pages, the admin panel and the SPA. Run after upgrading a font package.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const OUTPUT = 'packages/design-tokens/fonts.css';
const SUBSETS = ['cyrillic-ext', 'cyrillic', 'latin-ext', 'latin'];
const SOURCES = [
  '@fontsource-variable/inter/wght.css',
  '@fontsource-variable/roboto-condensed/wght.css',
  '@fontsource/jetbrains-mono/400.css',
];

function blocksFor(cssPath) {
  const css = readFileSync(cssPath, 'utf8');
  const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face\s*\{[^}]*\}/g)];
  return blocks
    .filter(([, name]) => SUBSETS.some((subset) => name.includes(`-${subset}-`)))
    .map(([block]) => block.replace(/url\(\.\/files\/([^)]+)\)/g, 'url(/static/fonts/$1)'));
}

const designTokensDir = dirname(require.resolve('@learnly/design-tokens/theme.css'));
const blocks = SOURCES.flatMap((source) =>
  blocksFor(require.resolve(source, { paths: [designTokensDir] })),
);
const header =
  '/* Generated by scripts/build-fonts-css.mjs. Do not edit by hand. */\n' +
  '/* Font files are served by the server at /static/fonts (Cyrillic and Latin subsets). */\n\n';
writeFileSync(OUTPUT, `${header}${blocks.join('\n\n')}\n`);
console.log(`Wrote ${blocks.length} @font-face rules to ${join(OUTPUT)}`);
